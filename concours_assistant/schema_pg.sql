-- Schéma PostgreSQL (version en ligne, Supabase).
-- Les tables vivent dans le schéma « concours », qui N'EST PAS exposé par l'API publique de
-- Supabase : seules l'application et le robot (rôle dédié) y accèdent.

CREATE SCHEMA IF NOT EXISTS concours;
SET search_path TO concours;

CREATE TABLE IF NOT EXISTS concours (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url                         TEXT NOT NULL,
    url_canonique               TEXT NOT NULL UNIQUE,
    url_participation           TEXT,
    url_participation_canonique TEXT,
    empreinte                   TEXT NOT NULL,
    nom                         TEXT NOT NULL,
    organisateur                TEXT,
    source                      TEXT NOT NULL,
    texte_source                TEXT,
    gain_principal_eur          DOUBLE PRECISION,
    dotation_totale_eur         DOUBLE PRECISION,
    date_limite                 TEXT,
    age_minimum                 INTEGER,
    url_reglement               TEXT,
    conditions                  TEXT NOT NULL DEFAULT '{}',
    mode_assistance             TEXT CHECK (mode_assistance IN ('preremplissage', 'manuel', 'abstention')),
    motifs                      TEXT NOT NULL DEFAULT '[]',
    avertissements              TEXT NOT NULL DEFAULT '[]',
    statut                      TEXT NOT NULL DEFAULT 'nouveau' CHECK (statut IN (
                                    'nouveau', 'a_verifier', 'exclu', 'pret',
                                    'intervention_humaine', 'inscrit', 'abandonne', 'erreur')),
    date_decouverte             TEXT NOT NULL,
    date_analyse                TEXT,
    date_inscription            TEXT,
    preuve                      TEXT,
    maj_le                      TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_concours_statut    ON concours(statut);
CREATE INDEX IF NOT EXISTS idx_concours_empreinte ON concours(empreinte);
CREATE INDEX IF NOT EXISTS idx_concours_url_part  ON concours(url_participation_canonique);

CREATE TABLE IF NOT EXISTS domaines (
    domaine                  TEXT PRIMARY KEY,
    automatisation_autorisee INTEGER NOT NULL DEFAULT 0,
    justification            TEXT,
    verifie_le               TEXT,
    bloque_jusqu_au          TEXT,
    raison_blocage           TEXT,
    dernier_acces            DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS consentements (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version    TEXT NOT NULL,
    accorde_le TEXT NOT NULL,
    retire_le  TEXT
);

CREATE TABLE IF NOT EXISTS journal (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    horodatage  TEXT NOT NULL,
    type        TEXT NOT NULL,
    concours_id BIGINT REFERENCES concours(id) ON DELETE SET NULL,
    domaine     TEXT,
    details     TEXT NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS idx_journal_horodatage ON journal(horodatage);

CREATE TABLE IF NOT EXISTS parametres (
    cle    TEXT PRIMARY KEY,
    valeur TEXT NOT NULL,
    maj_le TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS robots_cache (
    origine     TEXT PRIMARY KEY,
    statut      INTEGER NOT NULL,
    contenu     TEXT,
    recupere_le TEXT NOT NULL
);
